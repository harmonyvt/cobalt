// `npm run gen` (APP-API-CONTRACT.md 33.13): everything generated from the op registry, written next to what it
// describes and checked in.
//
//  - deploy/cloudflare/api/openapi.json: every API route (method, path, auth, CORS, the input check, the reply shape
//    where the op has one), OpenAPI 3.1.
//  - deploy/cloudflare/APP-API-CONTRACT.md: the route index table between its `routes:begin` / `routes:end` markers.
//  - apple/CobaltKit/Sources/CobaltKit/API/Generated/Endpoints.swift: one typed endpoint per route, and the Swift
//    reply types of the routes that have a shape.
//
// `npm run gen -- --check` writes nothing and fails when any output is stale (CI runs it).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import * as z from "zod";
import { REGISTRY } from "../src/registry/index";
import type { Op } from "../src/registry/op";

type Json = Record<string, any>;

export type Outputs = { openapi: string; contract: string; swift: string };

export const ROUTES_BEGIN = "<!-- routes:begin (generated by `npm run gen` in deploy/cloudflare/api; do not edit) -->";
export const ROUTES_END = "<!-- routes:end -->";

// ---- JSON Schema ----------------------------------------------------------------------------------------------------

const SAFE = 9007199254740991;

// A zod schema as JSON Schema, its named shapes (`.meta({ id })`) moved to `components`.
function jsonSchema(schema: z.ZodType, components: Json): Json {
    const raw = z.toJSONSchema(schema, { target: "draft-2020-12", unrepresentable: "any", io: "output" }) as Json;
    const defs: Json = raw.$defs ?? {};
    delete raw.$defs;
    delete raw.$schema;
    const fix = (v: any): any => {
        if (Array.isArray(v)) return v.map(fix);
        if (!v || typeof v !== "object") return v;
        const out: Json = {};
        for (const [k, x] of Object.entries(v)) {
            if (k === "$ref" && typeof x === "string") out[k] = x.replace("#/$defs/", "#/components/schemas/");
            // integers carry JavaScript's safe range by default: noise in a contract
            else if ((k === "minimum" && x === -SAFE) || (k === "maximum" && x === SAFE)) continue;
            else out[k] = fix(x);
        }
        return out;
    };
    for (const [id, def] of Object.entries(defs)) {
        const fixed = fix(def);
        const had = components[id];
        if (had && JSON.stringify(had) !== JSON.stringify(fixed)) throw new Error(`schema ${id} is defined two ways`);
        components[id] = fixed;
    }
    return fix(raw);
}

const isPlainObject = (s: Json) => s.type === "object" && s.properties && Object.keys(s.properties).length > 0;

// ---- OpenAPI ----------------------------------------------------------------------------------------------------------

const apiRoutes = (): Op[] => REGISTRY.ops.filter((o) => o.route && (o.route.host ?? "api") === "api");

const openApiPath = (path: string) => path.replace(/:([A-Za-z_]+)/g, "{$1}");

const AUTH_TEXT: Record<Op["auth"], string> = {
    key: "Api-Key client key (the library service gets 404)",
    key_or_service: "Api-Key client key or the library service",
    service: "the library service only",
    open: "none",
    capability: "none: the path's id is the credential",
};

function operation(op: Op, components: Json): Json {
    const route = op.route!;
    const params = [...route.path.matchAll(/:([A-Za-z_]+)/g)].map((m) => m[1]!);
    const parameters: Json[] = params.map((name) => ({
        name,
        in: "path",
        required: true,
        schema: { type: "string", ...(route.params?.[name] ? { pattern: route.params[name]!.source } : {}) },
    }));
    const out: Json = {
        operationId: op.name,
        summary: op.ai.summary.split("\n")[0],
        tags: [op.name.split(".")[0]!],
    };
    // the input check: query parameters (GET, HEAD, DELETE) or a JSON body, unless the handler reads the request itself
    const input = jsonSchema(op.input, components);
    const hasBody = route.method === "POST" || route.method === "PUT" || route.method === "PATCH";
    if (!op.http && isPlainObject(input)) {
        const props: Json = { ...input.properties };
        for (const p of params) delete props[p];
        const required = (input.required ?? []).filter((r: string) => !params.includes(r));
        if (hasBody && Object.keys(props).length > 0) {
            out.requestBody = {
                required: required.length > 0,
                content: { "application/json": { schema: { ...input, properties: props, required } } },
            };
        } else if (!hasBody) {
            for (const [name, schema] of Object.entries(props)) parameters.push({ name, in: "query", required: required.includes(name), schema });
        }
    }
    if (parameters.length > 0) out.parameters = parameters;
    out.responses = op.output
        ? { "200": { description: "success", content: { "application/json": { schema: jsonSchema(op.output, components) } } } }
        : { default: { description: op.raw ? "the handler's own response (see the contract)" : "JSON, as the contract describes" } };
    if (op.auth === "key" || op.auth === "key_or_service") out.security = [{ apiKey: [] }];
    else if (op.auth === "service") out.security = [{ service: [] }];
    else out.security = [];
    out["x-cobalt"] = {
        auth: op.auth,
        runs: op.runs,
        cors: op.cors,
        ...(op.noStore ? { no_store: true } : {}),
        ...(op.raw ? { raw: true } : {}),
        ...(op.http ? { input: "read by the handler" } : {}),
        ai: op.ai.tier,
    };
    return out;
}

export function openApi(): Json {
    const components: Json = {};
    const paths: Json = {};
    for (const op of apiRoutes()) {
        const p = openApiPath(op.route!.path);
        (paths[p] ??= {})[op.route!.method.toLowerCase()] = operation(op, components);
    }
    const sorted: Json = {};
    for (const k of Object.keys(paths).sort()) sorted[k] = paths[k];
    const schemas: Json = {};
    for (const k of Object.keys(components).sort()) schemas[k] = components[k];
    return {
        openapi: "3.1.0",
        info: {
            title: "capystore API (harmonyvt/cobalt Worker)",
            version: "1",
            description: "Generated from the op registry (deploy/cloudflare/api/src/registry). The contract is deploy/cloudflare/APP-API-CONTRACT.md.",
        },
        servers: [{ url: "https://api.capybaraharmony.com" }],
        paths: sorted,
        components: {
            schemas,
            securitySchemes: {
                apiKey: { type: "apiKey", in: "header", name: "Authorization", description: "`Api-Key <uuid>`" },
                service: { type: "apiKey", in: "header", name: "x-cobalt-service", description: "the web Worker's library service" },
            },
        },
    };
}

// ---- the contract's route index ----------------------------------------------------------------------------------------

export function routeTable(): string {
    const rows = REGISTRY.ops
        .filter((o) => o.route)
        .map((o) => {
            const r = o.route!;
            const host = r.host ?? "api";
            const path = host === "api" ? r.path : `${host} host ${r.path}`;
            return { host, path, method: r.method, o };
        })
        .sort((a, b) => (a.host === b.host ? 0 : a.host === "api" ? -1 : b.host === "api" ? 1 : a.host < b.host ? -1 : 1) || (a.path < b.path ? -1 : a.path > b.path ? 1 : 0) || (a.method < b.method ? -1 : 1));
    const yes = (b: boolean | undefined) => (b ? "yes" : "");
    const lines = [
        "| Method | Path | Op | Auth | CORS | No-store | Runs | Raw | Chat |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
        ...rows.map(
            ({ path, method, o }) =>
                `| ${method} | \`${path}\` | \`${o.name}\` | ${o.auth} | ${yes(o.cors)} | ${yes(o.noStore)} | ${o.runs === "durable_object" ? "DO" : "Worker"} | ${yes(o.raw)} | ${o.ai.tier === "hidden" ? "" : o.ai.tier} |`,
        ),
    ];
    const chat = REGISTRY.ops.filter((o) => o.ai.tier !== "hidden").map((o) => `\`cobalt.${o.callName}\`${o.ai.tier === "ask" ? " (asks first)" : ""}`);
    return [
        ROUTES_BEGIN,
        "",
        `${rows.length} routes, each one op in \`deploy/cloudflare/api/src/registry/ops/\` (section 33). Auth: \`key\` is a client`,
        "`Api-Key` (the library service gets 404), `key_or_service` also takes the library service, `service` takes only the",
        "service, `open` reads no key, `capability` means the path's id is the credential. Raw: the handler answers with its own",
        "Response (streams, uploads, file bytes, forwarding). Chat: the op is also a chat AI call. The machine-readable form is",
        "`deploy/cloudflare/api/openapi.json`.",
        "",
        ...lines,
        "",
        ...wrap(`The chat AI's calls (${chat.length}): ${chat.join(", ")}.`),
        "",
        ROUTES_END,
    ].join("\n");
}

// A paragraph cut into lines of about 120 characters, at spaces.
function wrap(text: string, width = 120): string[] {
    const lines: string[] = [];
    let line = "";
    for (const word of text.split(" ")) {
        if (line && line.length + 1 + word.length > width) {
            lines.push(line);
            line = word;
        } else line = line ? `${line} ${word}` : word;
    }
    if (line) lines.push(line);
    return lines;
}

export function withRouteTable(contract: string): string {
    const a = contract.indexOf(ROUTES_BEGIN);
    const b = contract.indexOf(ROUTES_END);
    if (a < 0 || b < a) throw new Error("APP-API-CONTRACT.md has no routes:begin / routes:end markers");
    return contract.slice(0, a) + routeTable() + contract.slice(b + ROUTES_END.length);
}

// ---- Swift ------------------------------------------------------------------------------------------------------------

const SWIFT_KEYWORDS = new Set(["public", "private", "internal", "default", "case", "class", "struct", "enum", "func", "var", "let", "in", "is", "as", "for", "while", "repeat", "return", "self", "Type", "protocol", "extension", "import", "static", "switch", "where", "true", "false", "nil", "operator", "subscript", "init", "deinit", "do", "catch", "try", "throw", "throws", "if", "else", "guard", "break", "continue", "fallthrough", "defer", "inout", "typealias", "associatedtype"]);

// What JSONDecoder's convertFromSnakeCase makes of a key: "set_ids" -> "setIds".
const camel = (key: string) => key.replace(/_+([a-z0-9])/g, (_, c: string) => c.toUpperCase());
const pascal = (s: string) =>
    s
        .split(/[._\-]/)
        .filter(Boolean)
        .map((p) => p[0]!.toUpperCase() + p.slice(1))
        .join("");
const ident = (s: string) => (SWIFT_KEYWORDS.has(s) ? `\`${s}\`` : s);
const swiftFuncName = (opName: string) => {
    const p = pascal(opName);
    return ident(p[0]!.toLowerCase() + p.slice(1));
};

type SwiftCtx = { components: Json; structs: string[]; named: Set<string> };

const refName = (ref: string) => ref.slice(ref.lastIndexOf("/") + 1);

// The Swift type of a schema; a nested object becomes a struct named after where it sits.
function swiftType(s: Json, where: string, cx: SwiftCtx, inArray = false): string | null {
    if (s.$ref) {
        const id = refName(s.$ref);
        const target = cx.components[id] ?? {};
        if (target["x-swift"]) return inArray ? `Lossy<${target["x-swift"]}>` : target["x-swift"];
        if (!cx.named.has(id)) {
            cx.named.add(id);
            swiftStruct(id, target, cx);
        }
        return id;
    }
    if (s["x-swift"]) return inArray ? `Lossy<${s["x-swift"]}>` : s["x-swift"];
    const types: string[] = Array.isArray(s.type) ? s.type : s.type ? [s.type] : [];
    const nonNull = types.filter((t) => t !== "null");
    const nullable = types.includes("null") || (Array.isArray(s.anyOf) && s.anyOf.some((x: Json) => x.type === "null"));
    if (Array.isArray(s.anyOf) && nonNull.length === 0) {
        const rest = s.anyOf.filter((x: Json) => x.type !== "null");
        if (rest.length !== 1) return null;
        const t = swiftType(rest[0], where, cx, inArray);
        return t && nullable ? `${t}?` : t;
    }
    if (nonNull.length !== 1) return null;
    let t: string | null;
    switch (nonNull[0]) {
        case "string":
            t = "String";
            break;
        case "integer":
            t = "Int";
            break;
        case "number":
            t = "Double";
            break;
        case "boolean":
            t = "Bool";
            break;
        case "array": {
            const item = s.items ? swiftType(s.items, `${where}Item`, cx, true) : null;
            t = item ? `[${item}]` : null;
            break;
        }
        case "object":
            if (!s.properties || Object.keys(s.properties).length === 0) return null;
            swiftStruct(where, s, cx);
            t = where;
            break;
        default:
            t = null;
    }
    return t && nullable ? `${t}?` : t;
}

function swiftStruct(name: string, s: Json, cx: SwiftCtx): void {
    const required = new Set<string>(s.required ?? []);
    const fields: string[] = [];
    for (const [key, prop] of Object.entries<Json>(s.properties ?? {})) {
        const t = swiftType(prop, `${name}${pascal(key)}`, cx);
        // a field with no Swift shape (unknown, a union) is left out: the decoder ignores what it does not name
        if (!t) continue;
        const optional = !required.has(key) && !t.endsWith("?") ? "?" : "";
        if (prop.description) fields.push(`    /// ${prop.description}`);
        fields.push(`    var ${ident(camel(key))}: ${t}${optional}`);
    }
    const doc = s.description ? `/// ${s.description}\n` : "";
    cx.structs.push(`${doc}struct ${name}: Decodable, Sendable {\n${fields.join("\n")}\n}`);
}

export function swiftClient(): string {
    const components: Json = {};
    // the components first (named shapes come out of the ops' schemas)
    for (const op of apiRoutes()) if (op.output) jsonSchema(op.output, components);
    const cx: SwiftCtx = { components, structs: [], named: new Set() };
    const funcs: string[] = [];
    const names = new Set<string>();
    for (const op of apiRoutes()) {
        const fn = swiftFuncName(op.name);
        if (names.has(fn)) throw new Error(`two ops make the Swift endpoint ${fn}`);
        names.add(fn);
        const route = op.route!;
        const params = [...route.path.matchAll(/:([A-Za-z_]+)/g)].map((m) => m[1]!);
        let response = "APIUntyped";
        if (op.output) {
            const name = `${pascal(op.name)}Response`;
            const t = swiftType(jsonSchema(op.output, components), name, cx);
            if (t) response = t;
        }
        const path = route.path.replace(/:([A-Za-z_]+)/g, (_, p: string) => `\\(HTTPCobaltClient.encode(${ident(camel(p))}))`);
        const args = params.map((p) => `${ident(camel(p))}: String`).join(", ");
        funcs.push(
            [
                `    /// \`${route.method} ${route.path}\` (op \`${op.name}\`, auth ${op.auth}): ${op.ai.summary.split("\n")[0]}`,
                `    static func ${swiftFuncName(op.name)}(${args}) -> APIEndpoint<${response}> {`,
                `        APIEndpoint(op: "${op.name}", method: "${route.method}", path: "${path}", auth: .${camel(op.auth)})`,
                `    }`,
            ].join("\n"),
        );
    }
    return [
        "// Generated by `npm run gen` in deploy/cloudflare/api from the op registry (APP-API-CONTRACT.md 33.13). Do not edit:",
        "// change the op (deploy/cloudflare/api/src/registry/) and run it again. CI fails when this file is stale.",
        "import Foundation",
        "",
        "/// Who may call a route (the op's `auth`).",
        "enum APIAuth: String, Sendable {",
        '    case key, keyOrService = "key_or_service", service, open, capability',
        "    /// The request carries the client key.",
        "    var keyed: Bool { self == .key || self == .keyOrService }",
        "}",
        "",
        "/// One route: its method and path (ids already escaped), and the reply type when the op has a shape.",
        "struct APIEndpoint<Response: Decodable & Sendable>: Sendable {",
        "    let op: String",
        "    let method: String",
        "    let path: String",
        "    let auth: APIAuth",
        "}",
        "",
        "/// The reply of a route whose op has no shape yet: decode it by hand.",
        "struct APIUntyped: Decodable, Sendable {}",
        "",
        "enum Endpoints {",
        funcs.join("\n\n"),
        "}",
        "",
        "// MARK: - Reply types",
        "",
        cx.structs.join("\n\n"),
        "",
    ].join("\n");
}

// ---- main ---------------------------------------------------------------------------------------------------------------

export function outputs(contract: string): Outputs {
    return { openapi: JSON.stringify(openApi(), null, 2) + "\n", contract: withRouteTable(contract), swift: swiftClient() };
}

export function main(root: string, check: boolean): number {
    const files = {
        openapi: resolve(root, "deploy/cloudflare/api/openapi.json"),
        contract: resolve(root, "deploy/cloudflare/APP-API-CONTRACT.md"),
        swift: resolve(root, "apple/CobaltKit/Sources/CobaltKit/API/Generated/Endpoints.swift"),
    };
    const want = outputs(readFileSync(files.contract, "utf8"));
    let stale = 0;
    for (const k of Object.keys(files) as (keyof Outputs)[]) {
        let have = "";
        try {
            have = readFileSync(files[k], "utf8");
        } catch {}
        if (have === want[k]) continue;
        if (check) {
            console.error(`stale: ${files[k]} (run \`npm run gen\` in deploy/cloudflare/api)`);
            stale++;
        } else {
            mkdirSync(dirname(files[k]), { recursive: true });
            writeFileSync(files[k], want[k]);
            console.log(`wrote ${files[k]}`);
        }
    }
    if (check && stale === 0) console.log("generated files are up to date");
    return stale === 0 ? 0 : 1;
}
